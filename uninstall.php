<?php
/**
 * Tasks to run during uninstallation of this plugin.
 *
 * @package next-meetup-hint
 */

// prevent direct access.
defined( 'ABSPATH' ) || exit;

use easySettingsForWordPress\Settings;

// if uninstall.php is not called by WordPress, die.
if ( ! defined( 'WP_UNINSTALL_PLUGIN' ) ) {
	die;
}

/**
 * Delete the data of this plugin on the actual site.
 *
 * @return void
 */
function next_meetup_hint_uninstall_site(): void {
	global $wpdb;

	// delete the transient of versions before 3.2.0.
	delete_transient( 'next_meetup_hint' );

	// delete the cached events of all users with one query, instead of loading every user.
	// phpcs:ignore WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching
	$wpdb->query(
		$wpdb->prepare(
			"DELETE FROM {$wpdb->options} WHERE option_name LIKE %s OR option_name LIKE %s",
			$wpdb->esc_like( '_transient_next_meetup_hint_' ) . '%',
			$wpdb->esc_like( '_transient_timeout_next_meetup_hint_' ) . '%'
		)
	);

	// delete all settings.
	foreach ( array( 'nmh_days_before', 'nmh_hide_days', 'nmh_ics', 'nmh_google_maps', 'nmh_openstreet_map', 'nmh_bing_maps', 'nmh_roles', 'nmh_hide_users', 'nextMeetupHint' ) as $option ) {
		delete_option( $option );
	}

	// delete the data the settings library saves itself.
	if ( class_exists( Settings::class ) ) {
		$settings_obj = new Settings( __FILE__ );
		$settings_obj->delete_settings();
	}
}

// get autoloader generated by composer.
if ( file_exists( __DIR__ . '/vendor/autoload.php' ) ) {
	require_once __DIR__ . '/vendor/autoload.php';
}

// delete the settings on user profiles. They are saved once for the whole network.
foreach ( array( 'hide_next_meet_hint', 'next_meet_hint_days', 'hide_next_meetup_hint_for_2_days' ) as $next_meetup_hint_meta_key ) {
	delete_metadata( 'user', 0, $next_meetup_hint_meta_key, '', true );
}

// delete the data on each site.
if ( is_multisite() ) {
	foreach ( get_sites(
		array(
			'fields' => 'ids',
			'number' => 0,
		)
	) as $next_meetup_hint_site_id ) {
		switch_to_blog( (int) $next_meetup_hint_site_id );
		next_meetup_hint_uninstall_site();
		restore_current_blog();
	}
} else {
	next_meetup_hint_uninstall_site();
}
