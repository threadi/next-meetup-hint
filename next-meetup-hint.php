/**
 * Return the values of a setting, which saves a list.
 *
 * @param string $option The name of the option.
 *
 * @return array<int,string>|null Null if the option is not saved yet.
 */
function next_meetup_hint_get_list_option( string $option ): ?array {
	// get the value.
	$value = get_option( $option );

	// bail if the option is not saved yet.
	if ( false === $value ) {
		return null;
	}

	// bail if the value is not a list.
	if ( ! is_array( $value ) ) {
		return array();
	}

	// return the scalar entries as strings.
	return array_values( array_map( 'strval', array_filter( $value, 'is_scalar' ) ) );
}

/**
 * Return whether next meetup hint is allowed for user.
 *
 * @param int $user_id The user to check.
 *
 * @return bool
 */
function next_meetup_hint_is_user_allowed( int $user_id ): bool {
	// get the user object.
	$user_obj = get_userdata( $user_id );

	// bail if no user could be loaded.
	if ( ! $user_obj instanceof WP_User ) {
		return false;
	}

	// bail if user is in list to hide the next meetup hint.
	if ( in_array( (string) $user_id, (array) next_meetup_hint_get_list_option( 'nmh_hide_users' ), true ) ) {
		return false;
	}

	// get the list of allowed roles. If it is not saved yet, all roles are allowed (the default of this setting).
	$allowed_roles = next_meetup_hint_get_list_option( 'nmh_roles' );
	if ( null === $allowed_roles ) {
		return true;
	}

	// return whether user has one of the allowed roles.
	return ! empty( array_intersect( $user_obj->roles, $allowed_roles ) );
}

