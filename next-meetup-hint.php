/**
 * Return the event for the next meetup the given user should see, or false if there is none.
 *
 * The result is cached per user for one hour, so the events are not requested on every page load.
 *
 * @param int $user_id The user ID.
 *
 * @return array<string,mixed>|false
 */
function next_meetup_hint_get_event( int $user_id ): array|false {
	// cache the result for this request, as this function is called several times per page load.
	static $events = array();
	if ( isset( $events[ $user_id ] ) ) {
		return $events[ $user_id ];
	}
	$events[ $user_id ] = false;

	// bail if no user is logged in.
	if ( $user_id <= 0 ) {
		return false;
	}

	// bail if next meetup hint is not allowed for this user.
	if ( ! next_meetup_hint_is_user_allowed( $user_id ) ) {
		return false;
	}

	// bail if the user has hidden the hint.
	if ( next_meetup_hint_is_hidden_for_user( $user_id ) ) {
		return false;
	}

	// use the cached result for this user, if there is one.
	$cache_key = next_meetup_hint_get_cache_key( $user_id );
	$cached    = get_transient( $cache_key );
	if ( is_array( $cached ) && array_key_exists( 'event', $cached ) ) {
		$events[ $user_id ] = is_array( $cached['event'] ) ? $cached['event'] : false;
		return $events[ $user_id ];
	}

	// search the event and save the result, also if no event has been found.
	$event = next_meetup_hint_find_event( $user_id );
	set_transient( $cache_key, array( 'event' => $event ), HOUR_IN_SECONDS );

	// return the result.
	$events[ $user_id ] = $event;
	return $event;
}

/**
 * Return the name of the transient which caches the event for a user.
 *
 * @param int $user_id The user ID.
 *
 * @return string
 */
function next_meetup_hint_get_cache_key( int $user_id ): string {
	return 'next_meetup_hint_' . $user_id;
}

/**
 * Load the events for the location of the user and return the first one within the configured days.
 *
 * @param int $user_id The user ID.
 *
 * @return array<string,mixed>|false
 */
function next_meetup_hint_find_event( int $user_id ): array|false {
	// get the location the user has saved in the dashboard widget "WordPress Events and News".
	$saved_location = get_user_option( 'community-events-location', $user_id );

	// bail if the user has no location yet: then the dashboard widget has not been used, and we do not request
	// the events from here.
	if ( empty( $saved_location ) || ! is_array( $saved_location ) ) {
		return false;
	}

	// embed the required object file for events from WordPress.
	require_once ABSPATH . 'wp-admin/includes/class-wp-community-events.php'; // @phpstan-ignore requireOnce.fileNotFound

	// get the list of events for this location. WordPress caches them itself.
	$events_client = new WP_Community_Events( $user_id, $saved_location );
	$events        = $events_client->get_events();

	// bail if it is an error or if no event list is found.
	if ( is_wp_error( $events ) || empty( $events['events'] ) || ! is_array( $events['events'] ) ) {
		return false;
	}

	// get the latest start of an event to show the hint for.
	$limit = time() + ( next_meetup_hint_get_days( $user_id ) * DAY_IN_SECONDS );

	// return the first event within this timeframe.
	foreach ( $events['events'] as $event ) {
		// bail if this is not a usable event.
		if ( ! is_array( $event ) || empty( $event['date'] ) ) {
			continue;
		}

		// bail if the event starts later.
		$start = next_meetup_hint_get_event_start( $event );
		if ( 0 === $start || $start > $limit ) {
			continue;
		}

		return $event;
	}

	// return false if no event has been found.
	return false;
}

/**
 * Return the start of an event as Unix timestamp.
 *
 * @param array<string,mixed> $event The event data.
 *
 * @return int
 */
function next_meetup_hint_get_event_start( array $event ): int {
	// use the exact timestamp, which WordPress adds to the event data.
	if ( ! empty( $event['start_unix_timestamp'] ) && is_numeric( $event['start_unix_timestamp'] ) ) {
		return absint( $event['start_unix_timestamp'] );
	}

	// otherwise use the local date of the event.
	if ( empty( $event['date'] ) || ! is_string( $event['date'] ) ) {
		return 0;
	}
	$start = strtotime( $event['date'] );
	return false === $start ? 0 : $start;
}

/**
 * Return the days before an event the hint should be shown to the user.
 *
 * @param int $user_id The user ID.
 *
 * @return int
 */
function next_meetup_hint_get_days( int $user_id ): int {
	// use the setting of the user.
	$days = absint( get_user_meta( $user_id, 'next_meet_hint_days', true ) );

	// if no user setting is given, use the global setting.
	if ( 0 === $days ) {
		$days = absint( get_option( 'nmh_days_before', 14 ) );
	}

	// return the days.
	return $days;
}

/**
 * Return the timestamp until the hint is hidden for the user, or 0 if it is not hidden temporarily.
 *
 * @param int $user_id The user ID.
 *
 * @return int
 */
function next_meetup_hint_get_hidden_until( int $user_id ): int {
	// get the time the user has hidden the hint.
	$hidden_at = absint( get_user_meta( $user_id, 'hide_next_meetup_hint_for_2_days', true ) );

	// bail if the user has not hidden the hint.
	if ( 0 === $hidden_at ) {
		return 0;
	}

	// calculate the end of this lock.
	$hidden_until = $hidden_at + ( absint( get_option( 'nmh_hide_days', 2 ) ) * DAY_IN_SECONDS );

	// return the end, if it is not reached yet.
	return $hidden_until > time() ? $hidden_until : 0;
}

/**
 * Return whether the user has hidden the hint, generally or temporarily.
 *
 * @param int $user_id The user ID.
 *
 * @return bool
 */
function next_meetup_hint_is_hidden_for_user( int $user_id ): bool {
	// return true if actual user has disabled the hint in its settings.
	if ( 1 === absint( get_user_meta( $user_id, 'hide_next_meet_hint', true ) ) ) {
		return true;
	}

	// return whether user has hidden the hint for some days.
	return next_meetup_hint_get_hidden_until( $user_id ) > 0;
}

/**
 * Show hint for next meetup.
 *
 * @return void
 */
function next_meetup_hint_notice(): void {
	// get the event for the actual user.
	$event = next_meetup_hint_get_event( get_current_user_id() );

	// bail if no event is found.
	if ( false === $event ) {
		return;
	}

	// output the template.
	require next_meetup_hint_get_template( 'event.php' );
}
