/**
 * Return a text, escaped for a value in an ICS file (RFC 5545, section 3.3.11).
 *
 * @param string $text The text.
 *
 * @return string
 */
function next_meetup_hint_ics_text( string $text ): string {
	// the events contain HTML entities, but ICS is plain text.
	$text = html_entity_decode( wp_strip_all_tags( $text ), ENT_QUOTES | ENT_HTML5, 'UTF-8' );

	// escape the special characters and line breaks.
	return str_replace(
		array( '\\', ';', ',', "\r\n", "\r", "\n" ),
		array( '\\\\', '\;', '\,', '\n', '\n', '\n' ),
		$text
	);
}

/**
 * Return a complete line for an ICS file: without control characters, folded after 75 octets, ending with CRLF.
 *
 * @param string $line The line.
 *
 * @return string
 */
function next_meetup_hint_ics_line( string $line ): string {
	// remove control characters, so a value can not start a new line.
	$line = (string) preg_replace( '/[\x00-\x1F\x7F]/', '', $line );

	// fold the line: a following line starts with a space, which counts for its length.
	$result  = '';
	$current = '';
	$chars   = preg_split( '//u', $line, -1, PREG_SPLIT_NO_EMPTY );
	foreach ( false === $chars ? array() : $chars as $char ) {
		$limit = '' === $result ? 75 : 74;
		if ( strlen( $current ) + strlen( $char ) > $limit ) {
			$result .= $current . "\r\n ";
			$current = '';
		}
		$current .= $char;
	}

	// return the resulting line.
	return $result . $current . "\r\n";
}

/**
 * Return the ICS of an event.
 *
 * @return void
 */
function next_meetup_hint_get_ics(): void {
	// check nonce.
	check_admin_referer( 'next-meetup-hint-ics', 'nonce' );

	// bail if option is not enabled.
	if ( 1 !== absint( get_option( 'nmh_ics' ) ) ) {
		wp_die( esc_html__( 'The download of meetups as ICS is disabled.', 'next-meetup-hint' ), '', array( 'response' => 403 ) );
	}

	// get the event of the actual user.
	$event = next_meetup_hint_get_event( get_current_user_id() );

	// bail if no event is found.
	if ( false === $event ) {
		wp_die(
			esc_html__( 'There is no upcoming meetup for you.', 'next-meetup-hint' ),
			'',
			array(
				'response'  => 404,
				'back_link' => true,
			)
		);
	}

	// create the filename.
	$filename   = sanitize_file_name( isset( $event['title'] ) && is_string( $event['title'] ) ? $event['title'] : '' );
	$ascii_name = (string) preg_replace( '/[^A-Za-z0-9._-]/', '', remove_accents( $filename ) );
	if ( '' === $ascii_name ) {
		$ascii_name = 'meetup';
	}
	if ( '' === $filename ) {
		$filename = $ascii_name;
	}

	// set header: the plain filename for old clients, the UTF-8 name for all others (RFC 6266).
	nocache_headers();
	header( 'Content-Type: text/calendar; charset=utf-8' );
	header( 'Content-Disposition: attachment; filename="' . $ascii_name . '.ics"; filename*=UTF-8\'\'' . rawurlencode( $filename . '.ics' ) );

	// output the ICS-template.
	require next_meetup_hint_get_template( 'ics.php' );
	exit;
}
add_action( 'admin_action_next_meetup_hint_ics', 'next_meetup_hint_get_ics' );
