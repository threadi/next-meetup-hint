/**
 * Run check for the active version to compile update tasks if necessary.
 *
 * @return void
 */
function next_meetup_hint_check_version(): void {
	// get installed plugin-version (version of the actual files in this plugin).
	$installed_plugin_version = NEXT_MEETUP_HINT_VERSION;

	// get the database version (version, which was last installed).
	$db_plugin_version = (string) get_option( 'nextMeetupHint', '1.0.0' );

	// bail if we are in development-mode.
	if ( function_exists( 'wp_is_development_mode' ) && wp_is_development_mode( 'plugin' ) ) {
		return;
	}

	// bail if the version did not change.
	if ( ! version_compare( $installed_plugin_version, $db_plugin_version, '>' ) ) {
		return;
	}

	// initialize settings and save the defaults of new settings (existing values are kept).
	next_meetup_hint_add_settings();
	next_meetup_hint_get_settings_object()->activation();

	// remove the transient of versions before 3.2.0, which was used for all users.
	delete_transient( 'next_meetup_hint' );

	// save new plugin-version in the database.
	update_option( 'nextMeetupHint', $installed_plugin_version );
}
add_action( 'init', 'next_meetup_hint_check_version', 20 );

