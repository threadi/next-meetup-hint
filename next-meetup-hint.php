/**
 * Return path to the requested template.
 *
 * @param string $template The file name of the template.
 *
 * @return string
 */
function next_meetup_hint_get_template( string $template ): string {
	// use only our own templates.
	if ( ! in_array( $template, array( 'event.php', 'ics.php' ), true ) ) {
		$template = 'event.php';
	}

	// check if requested template exist in the theme.
	$theme_template = locate_template( trailingslashit( basename( __DIR__ ) ) . $template );
	if ( $theme_template ) {
		return $theme_template;
	}

	/**
	 * Set template directory.
	 *
	 * Defaults to our own plugin-directory. Return the name of a directory in the plugin directory
	 * or an absolute path. It must contain the directory "templates".
	 *
	 * @since 2.0.0 Available since 2.0.0.
	 * @since 3.2.0 Absolute paths are possible.
	 *
	 * @param string $directory The directory to use.
	 */
	$directory = (string) apply_filters( 'next_meetup_hint_set_template_directory', basename( __DIR__ ) );

	// get the path of this directory.
	if ( ! path_is_absolute( $directory ) ) {
		$directory = trailingslashit( WP_PLUGIN_DIR ) . $directory;
	}

	// use the template from this directory, if it exists.
	$plugin_template = trailingslashit( $directory ) . 'templates/' . $template;
	if ( file_exists( $plugin_template ) ) {
		return $plugin_template;
	}

	// return template of the plugin.
	return plugin_dir_path( __FILE__ ) . 'templates/' . $template;
}

