/**
 * Return whether this request could show or save our settings.
 *
 * Only these requests need the list of all users.
 *
 * @return bool
 */
function next_meetup_hint_is_settings_request(): bool {
	// backend pages and AJAX (e.g. the import of settings).
	if ( is_admin() ) {
		return true;
	}

	// WP CLI.
	if ( defined( 'WP_CLI' ) && WP_CLI ) {
		return true;
	}

	// REST API, used by the settings page in WordPress 7.0 or newer. It is not detected yet at the time of "init".
	$request_uri = isset( $_SERVER['REQUEST_URI'] ) ? sanitize_text_field( wp_unslash( $_SERVER['REQUEST_URI'] ) ) : '';
	return str_contains( $request_uri, '/' . rest_get_url_prefix() . '/' ) || str_contains( $request_uri, 'rest_route=' );
}

/**
 * Return the list of users for the setting "nmh_hide_users".
 *
 * @return array<int|string,string>
 */
function next_meetup_hint_get_user_options(): array {
	// bail if this request does not need the list.
	if ( ! next_meetup_hint_is_settings_request() ) {
		return array();
	}

	// get only ID and name of each user, not the complete user objects.
	$users = array();
	foreach ( get_users(
		array(
			'fields'  => array( 'ID', 'display_name' ),
			'orderby' => 'display_name',
		)
	) as $user ) {
		$users[ (string) $user->ID ] = (string) $user->display_name;
	}

	// return the list.
	return $users;
}

/**
 * Add settings for this plugin.
 *
 * @return void
 */
function next_meetup_hint_add_settings(): void {
	global $wp_roles;

	// run this only once per request.
	static $done = false;
	if ( $done ) {
		return;
	}
	$done = true;

	// bail if no roles could be loaded.
	if ( ! $wp_roles instanceof WP_Roles ) {
		return;
	}

	// get list of roles.
	$roles          = array();
	$roles_defaults = array();
	foreach ( $wp_roles->roles as $name => $role ) {
		// add this role to the list.
		$roles[ $name ]   = $role['name'];
		$roles_defaults[] = $name;
	}

	/**
	 * Configure the basic settings object.
	 */
	$settings_obj = next_meetup_hint_get_settings_object();
	$settings_obj->set_menu_title( __( 'Next Meetup Hint settings', 'next-meetup-hint' ) );
	$settings_obj->set_title( __( 'Settings for Next Meetup Hint', 'next-meetup-hint' ) );
	$settings_obj->set_menu_slug( 'next-meetup-hint' );
	$settings_obj->show_settings_link_in_plugin_list( true );
	if ( method_exists( $settings_obj, 'set_view' ) ) { // @phpstan-ignore function.alreadyNarrowedType
		$settings_obj->set_view( 'dataview' );
	}

	// get the settings page.
	$settings_page = $settings_obj->get_page( 'next-meetup-hint' );

	// bail if page could not be found.
	if ( ! $settings_page instanceof Page ) {
		return;
	}

	/**
	 * Configure the tab for the settings.
	 */
	$general_tab = $settings_page->add_tab( 'nmh_general', 10 );
	$general_tab->set_title( __( 'General Settings', 'next-meetup-hint' ) );
	$settings_page->set_default_tab( $general_tab );

	$permissions_tab = $settings_page->add_tab( 'nmh_permissions', 20 );
	$permissions_tab->set_title( __( 'Permissions', 'next-meetup-hint' ) );

	/**
	 * Configure all sections for this settings object.
	 */
	// add general settings section.
	$general_tab_general_section = $general_tab->add_section( 'settings_section_general', 10 );
	$general_tab_general_section->set_title( __( 'General Settings', 'next-meetup-hint' ) );
	$general_tab_general_section->set_setting( $settings_obj );

	// add permissions settings section.
	$permissions_tab_general_section = $permissions_tab->add_section( 'settings_section_permissions', 20 );
	$permissions_tab_general_section->set_title( __( 'Permissions', 'next-meetup-hint' ) );
	$permissions_tab_general_section->set_setting( $settings_obj );

	/**
	 * Configure settings for this plugin.
	 */
	// set global days before the hint should be shown.
	$setting = $settings_obj->add_setting( 'nmh_days_before' );
	$setting->set_section( $general_tab_general_section );
	$setting->set_type( 'integer' );
	$setting->set_default( 14 );
