/**
 * Return the coordinates of an event as strings, or false if there are none.
 *
 * @param array<string,mixed> $event The event data.
 *
 * @return array{0: string, 1: string}|false
 */
function next_meetup_hint_get_coordinates( array $event ): array|false {
	// bail if no location is given.
	if ( empty( $event['location'] ) || ! is_array( $event['location'] ) ) {
		return false;
	}

	// bail if lat or lon are not available.
	$location = $event['location'];
	if ( empty( $location['latitude'] ) || empty( $location['longitude'] ) || ! is_numeric( $location['latitude'] ) || ! is_numeric( $location['longitude'] ) ) {
		return false;
	}

	// return them as numbers in text form.
	return array( (string) (float) $location['latitude'], (string) (float) $location['longitude'] );
}

